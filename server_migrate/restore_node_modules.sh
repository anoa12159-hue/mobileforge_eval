#!/usr/bin/env bash
# server_migrate/restore_node_modules.sh
#
# 在新服务器上为所有"数据样本"项目重建 node_modules。
#
# 压包时为了瘦身，对每个生成的 React 项目（output/、experiments/.../runs/、
# analysis/）都排除了 node_modules/。本脚本在解压完代码与数据后递归扫描所有
# package.json，对缺失 node_modules 的目录执行 npm install。
#
# 策略与 designforge/agentic/core.py / designforge/baselines/common.py 中保持一致：
#   1) 优先用默认 registry: npm install --no-audit --no-fund
#   2) 失败则回退到镜像源: --registry https://registry.npmmirror.com/
#
# 用法：
#   bash server_migrate/restore_node_modules.sh                    # 默认扫 output experiments analysis
#   bash server_migrate/restore_node_modules.sh output/mobileforge # 只恢复指定子目录
#   JOBS=8 bash server_migrate/restore_node_modules.sh             # 并发 8 个 npm 任务
#   DRY_RUN=1 bash server_migrate/restore_node_modules.sh          # 只列出待安装目录，不实际跑
#   FORCE=1 bash server_migrate/restore_node_modules.sh            # 即使已有 node_modules 也重装
#
# 退出码：
#   0 全部成功，非 0 至少有一个目录安装失败（详见 log 文件）

set -uo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT_DIR="$(cd "$SCRIPT_DIR/.." && pwd)"
cd "$ROOT_DIR"

# ---------- 配置 ----------
JOBS="${JOBS:-4}"
DRY_RUN="${DRY_RUN:-0}"
FORCE="${FORCE:-0}"
FALLBACK_REGISTRY="${FALLBACK_REGISTRY:-https://registry.npmmirror.com/}"
NPM_TIMEOUT_SEC="${NPM_TIMEOUT_SEC:-600}"   # 单个目录 install 超时（秒）

LOG_DIR="$ROOT_DIR/server_migrate/.restore_logs"
SUMMARY_LOG="$LOG_DIR/summary.log"
FAIL_LIST="$LOG_DIR/failed.txt"
OK_LIST="$LOG_DIR/ok.txt"
SKIP_LIST="$LOG_DIR/skipped.txt"
mkdir -p "$LOG_DIR"
: > "$SUMMARY_LOG" : > "$FAIL_LIST" : > "$OK_LIST" : > "$SKIP_LIST"

# ---------- 颜色 ----------
if [[ -t 1 ]]; then
  C_RED=$'\033[31m'; C_GREEN=$'\033[32m'; C_YELLOW=$'\033[33m'
  C_BLUE=$'\033[34m'; C_DIM=$'\033[2m'; C_RESET=$'\033[0m'
else
  C_RED=""; C_GREEN=""; C_YELLOW=""; C_BLUE=""; C_DIM=""; C_RESET=""
fi

log() { printf '%s\n' "$*" | tee -a "$SUMMARY_LOG" >&2; }

# ---------- 前置检查 ----------
if ! command -v npm >/dev/null 2>&1; then
  log "${C_RED}[错误]${C_RESET} 未找到 npm，先按 MIGRATION.md 2.3 节安装 Node 20。"
  exit 127
fi
log "${C_BLUE}[环境]${C_RESET} node=$(node --version 2>/dev/null || echo '?')  npm=$(npm --version 2>/dev/null || echo '?')"
log "${C_BLUE}[环境]${C_RESET} 工作根目录=$ROOT_DIR"
log "${C_BLUE}[环境]${C_RESET} 并发 JOBS=$JOBS  DRY_RUN=$DRY_RUN  FORCE=$FORCE"

# ---------- 收集扫描目录 ----------
if [[ $# -gt 0 ]]; then
  SCAN_ROOTS=("$@")
else
  SCAN_ROOTS=()
  for d in output experiments analysis; do
    [[ -d "$d" ]] && SCAN_ROOTS+=("$d")
  done
fi
if [[ ${#SCAN_ROOTS[@]} -eq 0 ]]; then
  log "${C_YELLOW}[警告]${C_RESET} 没有可扫描的根目录（output/ experiments/ analysis/ 都不存在）"
  exit 0
fi
log "${C_BLUE}[扫描]${C_RESET} 根目录: ${SCAN_ROOTS[*]}"

# ---------- 找出所有 package.json 所在目录 ----------
mapfile -t PKG_DIRS < <(
  find "${SCAN_ROOTS[@]}" -type f -name package.json \
    -not -path '*/node_modules/*' \
    -not -path '*/.git/*' 2>/dev/null \
  | xargs -r -n1 dirname \
  | sort -u
)
TOTAL=${#PKG_DIRS[@]}
log "${C_BLUE}[扫描]${C_RESET} 共发现 $TOTAL 个含 package.json 的项目目录"

# ---------- 过滤出真正需要安装的目录 ----------
TODO=()
for d in "${PKG_DIRS[@]}"; do
  if [[ "$FORCE" == "1" ]]; then
    TODO+=("$d")
  elif [[ -d "$d/node_modules" ]] && [[ -n "$(ls -A "$d/node_modules" 2>/dev/null)" ]]; then
    echo "$d" >> "$SKIP_LIST"
  else
    TODO+=("$d")
  fi
done
NEED=${#TODO[@]}
SKIPPED=$(wc -l < "$SKIP_LIST" | tr -d ' ')
log "${C_BLUE}[计划]${C_RESET} 需要安装: $NEED   已就绪跳过: $SKIPPED   总计: $TOTAL"

if [[ $NEED -eq 0 ]]; then
  log "${C_GREEN}[完成]${C_RESET} 所有项目都已就绪，无需安装。"
  exit 0
fi

if [[ "$DRY_RUN" == "1" ]]; then
  log "${C_YELLOW}[DRY_RUN]${C_RESET} 以下目录将会执行 npm install："
  printf '  %s\n' "${TODO[@]}" | tee -a "$SUMMARY_LOG"
  exit 0
fi

# ---------- 单个目录的安装函数 ----------
install_one() {
  local dir="$1"
  local idx="$2"
  local total="$3"
  local log_file="$LOG_DIR/$(echo "$dir" | tr '/' '_').log"
  local cmd_default='npm install --no-audit --no-fund --prefer-offline'
  local cmd_fallback="npm install --no-audit --no-fund --registry $FALLBACK_REGISTRY"

  printf '%s[%d/%d]%s 安装 %s\n' "$C_DIM" "$idx" "$total" "$C_RESET" "$dir" >&2

  # 第一次尝试：默认 registry
  if timeout "$NPM_TIMEOUT_SEC" bash -c "cd \"$dir\" && $cmd_default" >"$log_file" 2>&1; then
    printf '%s[ok]%s %s\n' "$C_GREEN" "$C_RESET" "$dir" >&2
    echo "$dir" >> "$OK_LIST"
    return 0
  fi

  # 第二次尝试：回退镜像源
  printf '%s[retry-mirror]%s %s\n' "$C_YELLOW" "$C_RESET" "$dir" >&2
  if timeout "$NPM_TIMEOUT_SEC" bash -c "cd \"$dir\" && $cmd_fallback" >>"$log_file" 2>&1; then
    printf '%s[ok-mirror]%s %s\n' "$C_GREEN" "$C_RESET" "$dir" >&2
    echo "$dir" >> "$OK_LIST"
    return 0
  fi

  printf '%s[fail]%s %s  (log: %s)\n' "$C_RED" "$C_RESET" "$dir" "$log_file" >&2
  echo "$dir" >> "$FAIL_LIST"
  return 1
}
export -f install_one
export C_DIM C_RESET C_RED C_GREEN C_YELLOW LOG_DIR FALLBACK_REGISTRY NPM_TIMEOUT_SEC OK_LIST FAIL_LIST

# ---------- 并行执行 ----------
log "${C_BLUE}[开始]${C_RESET} 启动 $JOBS 路并发安装……"
i=0
for d in "${TODO[@]}"; do
  i=$((i+1))
  printf '%s\t%d\t%d\n' "$d" "$i" "$NEED"
done | xargs -P "$JOBS" -n1 -I{} bash -c '
  IFS=$'"'"'\t'"'"' read -r dir idx total <<< "{}"
  install_one "$dir" "$idx" "$total"
'

# ---------- 汇总 ----------
OK_N=$(wc -l < "$OK_LIST" | tr -d ' ')
FAIL_N=$(wc -l < "$FAIL_LIST" | tr -d ' ')
log ""
log "${C_BLUE}[汇总]${C_RESET} 成功: $OK_N   失败: $FAIL_N   跳过: $SKIPPED"
log "${C_BLUE}[日志]${C_RESET} 详细日志目录: $LOG_DIR"
if [[ $FAIL_N -gt 0 ]]; then
  log "${C_RED}[失败列表]${C_RESET} $FAIL_LIST"
  log "重跑失败项: FORCE=1 bash server_migrate/restore_node_modules.sh \$(cat $FAIL_LIST | xargs)"
  exit 1
fi
log "${C_GREEN}[完成]${C_RESET} 全部安装成功。"
