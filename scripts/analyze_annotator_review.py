"""
Annotator Review Quality Analysis
==================================

Quantifies the auto-annotation quality by comparing:
- metadata.json   (auto-generated by annotator) vs metadata.reviewed.json    (human-reviewed)
- test_cases.json (auto-generated)               vs test_cases.reviewed.json (human-reviewed)
- review_state.json                              (per-page / per-case verdicts)

Reports:
- Per-app pass / edit / reject rates (from review_state.json)
- Field-level diff stats on metadata.pages and test_cases.cases
- Aggregated across 29 apps

Output:
- experiments/annotator_review/REPORT.md
- experiments/annotator_review/per_app.json

Read-only on user data; writes only inside experiments/annotator_review/.
"""

from __future__ import annotations

import argparse
import json
from collections import Counter, defaultdict
from pathlib import Path
from typing import Any


# ----------------------------- IO helpers -----------------------------------

def load_json(path: Path) -> Any | None:
    if not path.exists():
        return None
    try:
        with path.open("r", encoding="utf-8") as f:
            return json.load(f)
    except json.JSONDecodeError:
        return None


def list_apps(root: Path) -> list[Path]:
    return sorted(p for p in root.iterdir() if p.is_dir() and not p.name.startswith("."))


# --------------------------- review_state stats -----------------------------

def review_state_summary(rs: dict) -> dict[str, Any]:
    page_counter: Counter[str] = Counter()
    case_counter: Counter[str] = Counter()
    for _, v in (rs.get("pages") or {}).items():
        page_counter[str(v.get("status", "unknown"))] += 1
    for _, v in (rs.get("cases") or {}).items():
        case_counter[str(v.get("status", "unknown"))] += 1
    return {
        "pages_total": sum(page_counter.values()),
        "pages_by_status": dict(page_counter),
        "cases_total": sum(case_counter.values()),
        "cases_by_status": dict(case_counter),
    }


# --------------------------- metadata diff ----------------------------------

PAGE_FIELDS = (
    "page_name",
    "page_type",
    "description",
    "keywords",
    "visual_anchors",
    "structural_features",
    "screenshot",
)


def index_pages(pages: list[dict]) -> dict[str, dict]:
    out: dict[str, dict] = {}
    for p in pages or []:
        key = str(p.get("page_name", "")).strip()
        if key:
            out[key] = p
    return out


def diff_pages(auto: list[dict], reviewed: list[dict]) -> dict[str, Any]:
    auto_idx = index_pages(auto)
    rev_idx = index_pages(reviewed)
    auto_keys = set(auto_idx)
    rev_keys = set(rev_idx)

    added = sorted(rev_keys - auto_keys)
    removed = sorted(auto_keys - rev_keys)
    common = sorted(auto_keys & rev_keys)

    field_changed: Counter[str] = Counter()
    pages_with_any_change = 0
    for k in common:
        any_change = False
        for f in PAGE_FIELDS:
            if auto_idx[k].get(f) != rev_idx[k].get(f):
                field_changed[f] += 1
                any_change = True
        if any_change:
            pages_with_any_change += 1

    return {
        "auto_count": len(auto_keys),
        "reviewed_count": len(rev_keys),
        "added": added,
        "removed": removed,
        "common_count": len(common),
        "pages_with_any_change": pages_with_any_change,
        "field_changed_count": dict(field_changed),
    }


# ------------------------- test_cases diff ----------------------------------

CASE_TOP_FIELDS = ("type", "from_page", "action", "to_page", "assertions")
ACTION_SUB_FIELDS = (
    "description",
    "strategy",
    "tab_position",
    "text_hints",
    "dom_selector_hints",
)


def index_cases(cases: list[dict]) -> dict[str, dict]:
    out: dict[str, dict] = {}
    for c in cases or []:
        tid = str(c.get("test_id", "")).strip()
        if tid:
            out[tid] = c
    return out


def diff_cases(auto: list[dict], reviewed: list[dict]) -> dict[str, Any]:
    auto_idx = index_cases(auto)
    rev_idx = index_cases(reviewed)
    auto_keys = set(auto_idx)
    rev_keys = set(rev_idx)

    added = sorted(rev_keys - auto_keys)
    removed = sorted(auto_keys - rev_keys)
    common = sorted(auto_keys & rev_keys)

    field_changed: Counter[str] = Counter()
    action_field_changed: Counter[str] = Counter()
    cases_with_any_change = 0
    for k in common:
        a, r = auto_idx[k], rev_idx[k]
        any_change = False
        for f in CASE_TOP_FIELDS:
            if a.get(f) != r.get(f):
                field_changed[f] += 1
                any_change = True
                if f == "action":
                    aa, ra = (a.get("action") or {}), (r.get("action") or {})
                    for af in ACTION_SUB_FIELDS:
                        if aa.get(af) != ra.get(af):
                            action_field_changed[af] += 1
        if any_change:
            cases_with_any_change += 1

    return {
        "auto_count": len(auto_keys),
        "reviewed_count": len(rev_keys),
        "added": added,
        "removed": removed,
        "common_count": len(common),
        "cases_with_any_change": cases_with_any_change,
        "field_changed_count": dict(field_changed),
        "action_field_changed_count": dict(action_field_changed),
    }


# --------------------------- per-app summary --------------------------------

def analyze_app(app_dir: Path) -> dict[str, Any] | None:
    meta_auto = load_json(app_dir / "metadata.json")
    meta_rev = load_json(app_dir / "metadata.reviewed.json")
    cases_auto = load_json(app_dir / "test_cases.json")
    cases_rev = load_json(app_dir / "test_cases.reviewed.json")
    rs = load_json(app_dir / "review_state.json")
    if rs is None and meta_auto is None:
        return None

    meta_diff = None
    if meta_auto and meta_rev:
        meta_diff = diff_pages(meta_auto.get("pages") or [], meta_rev.get("pages") or [])

    case_diff = None
    if cases_auto and cases_rev:
        case_diff = diff_cases(cases_auto.get("cases") or [], cases_rev.get("cases") or [])

    rs_summary = review_state_summary(rs) if rs else None

    return {
        "app": app_dir.name,
        "review_state": rs_summary,
        "metadata_diff": meta_diff,
        "test_cases_diff": case_diff,
        "annotator_model": (meta_auto or {}).get("annotation", {}).get("model"),
        "annotated_at": (meta_auto or {}).get("annotation", {}).get("annotated_at"),
        "reviewed_at": (meta_rev or {}).get("annotation", {}).get("reviewed_at"),
    }


# ---------------------------- aggregation -----------------------------------

def aggregate(results: list[dict[str, Any]]) -> dict[str, Any]:
    pages_total = 0
    pages_status: Counter[str] = Counter()
    cases_total = 0
    cases_status: Counter[str] = Counter()

    meta_pages_common = 0
    meta_pages_changed = 0
    meta_pages_added = 0
    meta_pages_removed = 0
    meta_field_counts: Counter[str] = Counter()

    case_total_common = 0
    case_changed = 0
    case_added = 0
    case_removed = 0
    case_field_counts: Counter[str] = Counter()
    action_field_counts: Counter[str] = Counter()

    for r in results:
        rs = r.get("review_state")
        if rs:
            pages_total += rs["pages_total"]
            for k, v in rs["pages_by_status"].items():
                pages_status[k] += v
            cases_total += rs["cases_total"]
            for k, v in rs["cases_by_status"].items():
                cases_status[k] += v

        md = r.get("metadata_diff")
        if md:
            meta_pages_common += md["common_count"]
            meta_pages_changed += md["pages_with_any_change"]
            meta_pages_added += len(md["added"])
            meta_pages_removed += len(md["removed"])
            for k, v in md["field_changed_count"].items():
                meta_field_counts[k] += v

        cd = r.get("test_cases_diff")
        if cd:
            case_total_common += cd["common_count"]
            case_changed += cd["cases_with_any_change"]
            case_added += len(cd["added"])
            case_removed += len(cd["removed"])
            for k, v in cd["field_changed_count"].items():
                case_field_counts[k] += v
            for k, v in cd["action_field_changed_count"].items():
                action_field_counts[k] += v

    return {
        "apps": len(results),
        "review_state_aggregate": {
            "pages_total": pages_total,
            "pages_by_status": dict(pages_status),
            "cases_total": cases_total,
            "cases_by_status": dict(cases_status),
        },
        "metadata_aggregate": {
            "pages_common_total": meta_pages_common,
            "pages_with_any_change": meta_pages_changed,
            "pages_added_total": meta_pages_added,
            "pages_removed_total": meta_pages_removed,
            "field_changed_count": dict(meta_field_counts),
        },
        "test_cases_aggregate": {
            "cases_common_total": case_total_common,
            "cases_with_any_change": case_changed,
            "cases_added_total": case_added,
            "cases_removed_total": case_removed,
            "field_changed_count": dict(case_field_counts),
            "action_field_changed_count": dict(action_field_counts),
        },
    }


# ----------------------------- markdown -------------------------------------

def pct(num: int, denom: int) -> str:
    if denom == 0:
        return "n/a"
    return f"{num / denom * 100:.1f}%"


def render_markdown(results: list[dict[str, Any]], agg: dict[str, Any]) -> str:
    lines: list[str] = []
    lines.append("# Annotator Auto vs Human Review Analysis")
    lines.append("")
    lines.append(f"> Apps analyzed: **{agg['apps']}**")
    lines.append("")
    lines.append("Two-stage annotation pipeline:")
    lines.append("")
    lines.append("1. **Auto stage** — VLM (gemini-2.5-flash) generates `metadata.json` (pages: name, type, description, keywords, visual anchors, structural features) and `test_cases.json` (per-test trigger, action, expected page).")
    lines.append("2. **Human review** — annotator opens a labeling UI; the reviewer can edit any field, add missing pages / cases, or delete spurious ones, and saves the corrected payload to `*.reviewed.json`. The `*.reviewed.json` is the **ground truth** used by the rest of the benchmark.")
    lines.append("")
    lines.append("> **Note on `status` in `review_state.json`**: in this dataset the reviewer's workflow saved every record as `status=pass` after editing rather than flipping it to `edit`, so the verdict field by itself is not informative. The signal lives in the field-level diff between `metadata.json` and `metadata.reviewed.json` (and analogously for test cases).")
    lines.append("")

    # ------------- precision / recall summary up front -------------
    md = agg["metadata_aggregate"]
    cd = agg["test_cases_aggregate"]
    page_auto = md["pages_common_total"] + md["pages_removed_total"]
    page_gt = md["pages_common_total"] + md["pages_added_total"]
    page_kept = md["pages_common_total"]
    page_kept_unchanged = page_kept - md["pages_with_any_change"]
    page_recall = pct(page_kept, page_gt)
    page_precision = pct(page_kept, page_auto)
    page_exact_precision = pct(page_kept_unchanged, page_auto)

    case_auto = cd["cases_common_total"] + cd["cases_removed_total"]
    case_gt = cd["cases_common_total"] + cd["cases_added_total"]
    case_kept = cd["cases_common_total"]
    case_kept_unchanged = case_kept - cd["cases_with_any_change"]
    case_recall = pct(case_kept, case_gt)
    case_precision = pct(case_kept, case_auto)
    case_exact_precision = pct(case_kept_unchanged, case_auto)

    lines.append("## 0. Headline numbers")
    lines.append("")
    lines.append("Treating `*.reviewed.json` as ground truth, we compute:")
    lines.append("")
    lines.append("- **Recall** = (auto records kept by reviewer) / (all reviewed records). Measures how many ground-truth records the annotator captured.")
    lines.append("- **Precision** = (auto records kept by reviewer) / (all auto records). Measures how often the annotator's outputs survive review.")
    lines.append("- **Exact-match precision** = (auto records kept *unchanged* by reviewer) / (all auto records). The strictest signal — record was not only retained but also bit-for-bit accepted.")
    lines.append("")
    lines.append("| Granularity | # Auto | # GT (reviewed) | # Kept | # Kept unchanged | Recall | Precision | Exact-match precision |")
    lines.append("|---|---|---|---|---|---|---|---|")
    lines.append(
        f"| Pages (`metadata.json`) | {page_auto} | {page_gt} | {page_kept} | {page_kept_unchanged} | "
        f"**{page_recall}** | **{page_precision}** | {page_exact_precision} |"
    )
    lines.append(
        f"| Test cases (`test_cases.json`) | {case_auto} | {case_gt} | {case_kept} | {case_kept_unchanged} | "
        f"**{case_recall}** | **{case_precision}** | {case_exact_precision} |"
    )
    lines.append("")
    lines.append("Interpretation:")
    lines.append("")
    lines.append(f"- The annotator captures **{page_recall}** of the ground-truth pages and **{case_recall}** of the ground-truth test cases — recall on test cases is meaningfully lower, the reviewer adds many cases the annotator missed.")
    lines.append(f"- Of the auto records that survive review, only the field-level diff (Section 2 / 3) tells how invasive the edit is. **{page_exact_precision}** of pages and **{case_exact_precision}** of cases are accepted bit-for-bit.")
    lines.append("- Most page edits target `page_type` and `structural_features`; most case edits target `action.description`, `action.dom_selector_hints` and `action.tab_position` — i.e. fields that directly drive the click model at test time.")
    lines.append("")

    # ------------------- review state global -------------------
    rs = agg["review_state_aggregate"]
    lines.append("## 1. Reviewer Verdicts (page- and case-level)")
    lines.append("")
    lines.append("### Pages")
    lines.append("")
    lines.append(f"Total pages reviewed: **{rs['pages_total']}**")
    lines.append("")
    lines.append("| Status | Count | Share |")
    lines.append("|---|---|---|")
    for k in ("pass", "edit", "reject", "skip", "unknown"):
        c = rs["pages_by_status"].get(k, 0)
        if c == 0:
            continue
        lines.append(f"| `{k}` | {c} | {pct(c, rs['pages_total'])} |")
    lines.append("")
    lines.append("### Test cases")
    lines.append("")
    lines.append(f"Total test cases reviewed: **{rs['cases_total']}**")
    lines.append("")
    lines.append("| Status | Count | Share |")
    lines.append("|---|---|---|")
    for k in ("pass", "edit", "reject", "skip", "unknown"):
        c = rs["cases_by_status"].get(k, 0)
        if c == 0:
            continue
        lines.append(f"| `{k}` | {c} | {pct(c, rs['cases_total'])} |")
    lines.append("")

    # -------------------- metadata diff global ------------------
    md = agg["metadata_aggregate"]
    lines.append("## 2. Field-level Edits on `metadata.json`")
    lines.append("")
    lines.append(f"Pages present in both auto and reviewed: **{md['pages_common_total']}**")
    lines.append("")
    lines.append(f"- Pages with any field change: **{md['pages_with_any_change']}** ({pct(md['pages_with_any_change'], md['pages_common_total'])})")
    lines.append(f"- Pages added by reviewer: **{md['pages_added_total']}**")
    lines.append(f"- Pages removed by reviewer: **{md['pages_removed_total']}**")
    lines.append("")
    lines.append("Edit counts per field (across all apps):")
    lines.append("")
    lines.append("| Field | # Pages with edit | Edit rate |")
    lines.append("|---|---|---|")
    for f in PAGE_FIELDS:
        c = md["field_changed_count"].get(f, 0)
        lines.append(f"| `{f}` | {c} | {pct(c, md['pages_common_total'])} |")
    lines.append("")

    # -------------------- test_cases diff global ----------------
    cd = agg["test_cases_aggregate"]
    lines.append("## 3. Field-level Edits on `test_cases.json`")
    lines.append("")
    lines.append(f"Test cases present in both auto and reviewed: **{cd['cases_common_total']}**")
    lines.append("")
    lines.append(f"- Cases with any field change: **{cd['cases_with_any_change']}** ({pct(cd['cases_with_any_change'], cd['cases_common_total'])})")
    lines.append(f"- Cases added by reviewer: **{cd['cases_added_total']}**")
    lines.append(f"- Cases removed by reviewer: **{cd['cases_removed_total']}**")
    lines.append("")
    lines.append("Edit counts per top-level field:")
    lines.append("")
    lines.append("| Field | # Cases with edit | Edit rate |")
    lines.append("|---|---|---|")
    for f in CASE_TOP_FIELDS:
        c = cd["field_changed_count"].get(f, 0)
        lines.append(f"| `{f}` | {c} | {pct(c, cd['cases_common_total'])} |")
    lines.append("")
    lines.append("Edit counts on the `action` sub-fields (this is what the click model later consumes):")
    lines.append("")
    lines.append("| Sub-field | # Cases with edit | Edit rate |")
    lines.append("|---|---|---|")
    for f in ACTION_SUB_FIELDS:
        c = cd["action_field_changed_count"].get(f, 0)
        lines.append(f"| `action.{f}` | {c} | {pct(c, cd['cases_common_total'])} |")
    lines.append("")

    # -------------------- per-app table ------------------------
    lines.append("## 4. Per-app Breakdown")
    lines.append("")
    lines.append("| App | Pages | Pages pass% | Pages edit% | Cases | Cases pass% | Cases edit% | Cases added | Cases removed |")
    lines.append("|---|---|---|---|---|---|---|---|---|")
    for r in results:
        rs = r.get("review_state") or {}
        cd = r.get("test_cases_diff") or {}
        pages_total = rs.get("pages_total", 0)
        pages_pass = rs.get("pages_by_status", {}).get("pass", 0)
        pages_edit = rs.get("pages_by_status", {}).get("edit", 0)
        cases_total = rs.get("cases_total", 0)
        cases_pass = rs.get("cases_by_status", {}).get("pass", 0)
        cases_edit = rs.get("cases_by_status", {}).get("edit", 0)
        added = len(cd.get("added", [])) if cd else 0
        removed = len(cd.get("removed", [])) if cd else 0
        lines.append(
            f"| `{r['app']}` | {pages_total} | {pct(pages_pass, pages_total)} | {pct(pages_edit, pages_total)} | "
            f"{cases_total} | {pct(cases_pass, cases_total)} | {pct(cases_edit, cases_total)} | {added} | {removed} |"
        )
    lines.append("")

    # -------------------- methodology footer ----------------------
    lines.append("## 5. Notes on metric interpretation")
    lines.append("")
    lines.append("- **`status==pass`** means the reviewer accepted the auto-generated record verbatim. This is the strongest signal of annotator correctness.")
    lines.append("- **`status==edit`** means the reviewer touched at least one field. Combined with the field-level diff above, this localizes *what* the annotator gets wrong most often.")
    lines.append("- **Pages added / removed** by the reviewer reflect annotator recall failures (missed pages) and false positives (hallucinated pages) respectively.")
    lines.append("- The page-level edit rate is an upper bound on annotator error: a reviewer may have edited only a single keyword and still flipped the status to `edit`. Use the per-field counts to weigh which edits matter (e.g. `action.dom_selector_hints` and `action.description` directly drive click-model behavior at test time).")
    lines.append("")
    return "\n".join(lines)


# --------------------------------- CLI --------------------------------------

def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--input",
        type=Path,
        default=Path("input/mobileforge"),
        help="Root directory containing one folder per app.",
    )
    parser.add_argument(
        "--out-dir",
        type=Path,
        default=Path("experiments/annotator_review"),
        help="Output directory (will be created).",
    )
    args = parser.parse_args()

    apps = list_apps(args.input)
    results: list[dict[str, Any]] = []
    for app_dir in apps:
        r = analyze_app(app_dir)
        if r:
            results.append(r)

    agg = aggregate(results)

    args.out_dir.mkdir(parents=True, exist_ok=True)
    (args.out_dir / "per_app.json").write_text(
        json.dumps({"per_app": results, "aggregate": agg}, ensure_ascii=False, indent=2),
        encoding="utf-8",
    )
    md = render_markdown(results, agg)
    (args.out_dir / "REPORT.md").write_text(md, encoding="utf-8")
    print(f"Wrote {args.out_dir / 'REPORT.md'} and {args.out_dir / 'per_app.json'}.")


if __name__ == "__main__":
    main()
